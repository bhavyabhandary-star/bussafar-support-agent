"""Human support tickets, saved in tickets.csv with a status and a history.

Ticket IDs (TKT-1001, TKT-1002, ...) are generated by code, never by the model,
and are never repeated. A ticket ID is only returned after the row has been
written and read back successfully.

Status lifecycle: Pending (just raised) -> In progress (a specialist is on it)
-> Done (resolved). Every change is appended to tickets_history.csv with the
time, the new status, a note and who made it. Tickets saved by older versions
with status "open" are read as Pending and upgraded on the next write.
"""
from __future__ import annotations

import csv
import os
import re
import time
from contextlib import contextmanager
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path

import config
from agent.guardrails import redact_pii

FIELDNAMES = [
    "ticket_id", "created_at", "customer_query", "category", "reason",
    "priority", "pnr", "conversation_summary", "status", "updated_at", "status_note",
]
HISTORY_FIELDNAMES = ["ticket_id", "at", "status", "note", "changed_by"]
STATUSES = ["Pending", "In progress", "Done"]
STATUS_MEANINGS = {
    "Pending": "Raised and waiting for a support specialist.",
    "In progress": "A support specialist is working on it.",
    "Done": "Resolved by our support team.",
}
_STATUS_ALIASES = {
    "pending": "Pending", "open": "Pending", "new": "Pending", "hold": "Pending", "on hold": "Pending",
    "in progress": "In progress", "in-progress": "In progress", "inprogress": "In progress",
    "working": "In progress", "assigned": "In progress",
    "done": "Done", "resolved": "Done", "closed": "Done", "complete": "Done", "completed": "Done",
}


def normalize_status(status: object) -> str | None:
    """Map any accepted spelling ("open", "resolved", "in-progress") to Pending / In progress / Done."""
    return _STATUS_ALIASES.get(str(status or "").strip().lower())
CATEGORIES = {
    "safety": "Safety concern during a trip",
    "bus_no_show": "Bus never came or left early",
    "refund_dispute": "Refund request or dispute",
    "lost_item": "Item left behind on the bus",
    "complaint": "Complaint or upset customer",
    "booking_discrepancy": "Booking discrepancy",
    "unresolved_query": "Answer not in help docs",
    "human_request": "Customer asked for a person",
    "other": "Other",
}
PRIORITIES = {"normal", "high"}
FIRST_TICKET_NUMBER = 1001
_ID_RE = re.compile(r"^TKT-(\d+)$")
_PNR_RE = re.compile(r"^BS\d{6}$")


class TicketError(RuntimeError):
    pass


@dataclass
class Ticket:
    ticket_id: str
    created_at: str
    customer_query: str
    category: str
    reason: str
    priority: str
    pnr: str
    conversation_summary: str
    status: str = "Pending"
    updated_at: str = ""
    status_note: str = ""


def _clean(text: object, limit: int) -> str:
    text = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", " ", str(text or ""))
    text = redact_pii(text).strip()
    return text[:limit]


class TicketManager:
    def __init__(self, path: Path | str = config.TICKETS_CSV) -> None:
        self.path = Path(path)
        self.lock_path = self.path.with_suffix(self.path.suffix + ".lock")
        self.history_path = self.path.with_name(self.path.stem + "_history.csv")

    @contextmanager
    def _lock(self, timeout: float = 5.0):
        deadline = time.monotonic() + timeout
        while True:
            try:
                fd = os.open(self.lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                break
            except FileExistsError:
                # Clear a stale lock left by a crashed process.
                try:
                    if time.time() - self.lock_path.stat().st_mtime > 30:
                        self.lock_path.unlink(missing_ok=True)
                        continue
                except FileNotFoundError:
                    continue
                if time.monotonic() > deadline:
                    raise TicketError("Ticket store is busy. Please try again.")
                time.sleep(0.05)
        try:
            yield
        finally:
            os.close(fd)
            self.lock_path.unlink(missing_ok=True)

    def _read_rows(self) -> list[dict]:
        if not self.path.exists():
            return []
        with self.path.open(newline="", encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        for r in rows:  # fill columns added in newer versions and normalise old statuses
            r["status"] = normalize_status(r.get("status")) or "Pending"
            r["updated_at"] = r.get("updated_at") or r.get("created_at", "")
            r["status_note"] = r.get("status_note") or ""
        return [{k: r.get(k, "") for k in FIELDNAMES} for r in rows]

    def _header_is_current(self) -> bool:
        if not self.path.exists() or self.path.stat().st_size == 0:
            return True
        with self.path.open(newline="", encoding="utf-8") as f:
            return next(csv.reader(f), []) == FIELDNAMES

    def _rewrite(self, rows: list[dict]) -> None:
        """Atomically replace tickets.csv (write a temp file, then swap it in)."""
        tmp = self.path.with_suffix(self.path.suffix + ".tmp")
        with tmp.open("w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
            writer.writeheader()
            writer.writerows(rows)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, self.path)

    def _log_history(self, ticket_id: str, status: str, note: str, changed_by: str, at: str) -> None:
        new_file = not self.history_path.exists() or self.history_path.stat().st_size == 0
        with self.history_path.open("a", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=HISTORY_FIELDNAMES)
            if new_file:
                writer.writeheader()
            writer.writerow({"ticket_id": ticket_id, "at": at, "status": status,
                             "note": note, "changed_by": changed_by})
            f.flush()
            os.fsync(f.fileno())

    def _next_id(self, rows: list[dict]) -> str:
        numbers = [int(m.group(1)) for r in rows if (m := _ID_RE.match(r.get("ticket_id", "")))]
        return f"TKT-{max(numbers) + 1 if numbers else FIRST_TICKET_NUMBER}"

    def create_ticket(
        self,
        customer_query: str,
        category: str,
        reason: str = "",
        priority: str = "normal",
        pnr: str | None = None,
        conversation_summary: str = "",
    ) -> Ticket:
        query = _clean(customer_query, 1000)
        if not query:
            raise TicketError("A ticket needs a description of the issue.")
        category = (category or "other").strip().lower()
        if category not in CATEGORIES:
            category = "other"
        priority = (priority or "normal").strip().lower()
        if priority not in PRIORITIES:
            priority = "normal"
        if category == "safety":
            priority = "high"
        pnr_clean = re.sub(r"\s+", "", str(pnr or "")).upper()
        if not _PNR_RE.match(pnr_clean):
            pnr_clean = ""
        self.path.parent.mkdir(parents=True, exist_ok=True)
        try:
            with self._lock():
                rows = self._read_rows()
                if not self._header_is_current():
                    self._rewrite(rows)  # upgrade a tickets.csv saved by an older version
                now = datetime.now(timezone.utc).isoformat(timespec="seconds")
                ticket = Ticket(
                    ticket_id=self._next_id(rows),
                    created_at=now,
                    updated_at=now,
                    customer_query=query,
                    category=category,
                    reason=_clean(reason, 300) or CATEGORIES[category],
                    priority=priority,
                    pnr=pnr_clean,
                    conversation_summary=_clean(conversation_summary, 2000),
                )
                new_file = not self.path.exists() or self.path.stat().st_size == 0
                with self.path.open("a", newline="", encoding="utf-8") as f:
                    writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
                    if new_file:
                        writer.writeheader()
                    writer.writerow(asdict(ticket))
                    f.flush()
                    os.fsync(f.fileno())
                # Read back to confirm the write before reporting success.
                if not any(r.get("ticket_id") == ticket.ticket_id for r in self._read_rows()):
                    raise TicketError("Ticket could not be verified after saving.")
                self._log_history(ticket.ticket_id, ticket.status, "ticket raised", "sahil", now)
        except OSError as exc:
            raise TicketError(f"Could not save the ticket: {exc}") from exc
        return ticket

    def update_status(self, ticket_id: str, status: str, note: str = "", changed_by: str = "staff") -> dict:
        """Move a ticket to Pending, In progress or Done. Returns the updated row; raises TicketError."""
        new_status = normalize_status(status)
        if not new_status:
            raise TicketError(f"Unknown status '{status}'. Use one of: {', '.join(STATUSES)}.")
        tid = _normalize_ticket_id(ticket_id)
        try:
            with self._lock():
                rows = self._read_rows()
                row = next((r for r in rows if r["ticket_id"] == tid), None)
                if row is None:
                    raise TicketError(f"No ticket {tid}.")
                now = datetime.now(timezone.utc).isoformat(timespec="seconds")
                row.update(status=new_status, updated_at=now, status_note=_clean(note, 500))
                self._rewrite(rows)
                self._log_history(tid, new_status, _clean(note, 500), _clean(changed_by, 60) or "staff", now)
        except OSError as exc:
            raise TicketError(f"Could not save the status change: {exc}") from exc
        return row

    def history(self, ticket_id: str) -> list[dict]:
        if not self.history_path.exists():
            return []
        tid = _normalize_ticket_id(ticket_id)
        with self.history_path.open(newline="", encoding="utf-8") as f:
            return [r for r in csv.DictReader(f) if r.get("ticket_id") == tid]

    def list_tickets(self, status: str | None = None) -> list[dict]:
        rows = self._read_rows()
        if status:
            wanted = normalize_status(status) or status
            rows = [r for r in rows if r.get("status") == wanted]
        return rows

    def get_ticket(self, ticket_id: str) -> dict | None:
        tid = _normalize_ticket_id(ticket_id)
        return next((r for r in self._read_rows() if r.get("ticket_id") == tid), None)


def _normalize_ticket_id(ticket_id: object) -> str:
    """'tkt-1001', 'TKT 1001' and '1001' all mean TKT-1001."""
    tid = re.sub(r"\s+", "", str(ticket_id or "")).upper()
    if tid.isdigit():
        tid = f"TKT-{tid}"
    return tid.replace("TKT", "TKT-").replace("TKT--", "TKT-") if tid.startswith("TKT") else tid
