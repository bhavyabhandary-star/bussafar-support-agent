"""Human support ticket creation, stored in tickets.csv.

Ticket IDs (TKT-1001, TKT-1002, ...) are generated by code, never by the model,
and are never repeated. A ticket ID is only returned after the row has been
written and read back successfully.
"""
from __future__ import annotations

import csv
import os
import re
import time
from contextlib import contextmanager
from dataclasses import asdict, dataclass
from datetime import datetime, timezone
from pathlib import Path

import config
from agent.guardrails import redact_pii

FIELDNAMES = [
    "ticket_id", "created_at", "customer_query", "category", "reason",
    "priority", "pnr", "conversation_summary", "status",
]
CATEGORIES = {
    "safety": "Safety concern during a trip",
    "bus_no_show": "Bus never came or left early",
    "refund_dispute": "Refund request or dispute",
    "lost_item": "Item left behind on the bus",
    "complaint": "Complaint or upset customer",
    "booking_discrepancy": "Booking discrepancy",
    "unresolved_query": "Answer not in help docs",
    "human_request": "Customer asked for a person",
    "other": "Other",
}
PRIORITIES = {"normal", "high"}
FIRST_TICKET_NUMBER = 1001
_ID_RE = re.compile(r"^TKT-(\d+)$")
_PNR_RE = re.compile(r"^BS\d{6}$")


class TicketError(RuntimeError):
    pass


@dataclass
class Ticket:
    ticket_id: str
    created_at: str
    customer_query: str
    category: str
    reason: str
    priority: str
    pnr: str
    conversation_summary: str
    status: str = "open"


def _clean(text: object, limit: int) -> str:
    text = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", " ", str(text or ""))
    text = redact_pii(text).strip()
    return text[:limit]


class TicketManager:
    def __init__(self, path: Path | str = config.TICKETS_CSV) -> None:
        self.path = Path(path)
        self.lock_path = self.path.with_suffix(self.path.suffix + ".lock")

    @contextmanager
    def _lock(self, timeout: float = 5.0):
        deadline = time.monotonic() + timeout
        while True:
            try:
                fd = os.open(self.lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
                break
            except FileExistsError:
                # Clear a stale lock left by a crashed process.
                try:
                    if time.time() - self.lock_path.stat().st_mtime > 30:
                        self.lock_path.unlink(missing_ok=True)
                        continue
                except FileNotFoundError:
                    continue
                if time.monotonic() > deadline:
                    raise TicketError("Ticket store is busy. Please try again.")
                time.sleep(0.05)
        try:
            yield
        finally:
            os.close(fd)
            self.lock_path.unlink(missing_ok=True)

    def _read_rows(self) -> list[dict]:
        if not self.path.exists():
            return []
        with self.path.open(newline="", encoding="utf-8") as f:
            return list(csv.DictReader(f))

    def _next_id(self, rows: list[dict]) -> str:
        numbers = [int(m.group(1)) for r in rows if (m := _ID_RE.match(r.get("ticket_id", "")))]
        return f"TKT-{max(numbers) + 1 if numbers else FIRST_TICKET_NUMBER}"

    def create_ticket(
        self,
        customer_query: str,
        category: str,
        reason: str = "",
        priority: str = "normal",
        pnr: str | None = None,
        conversation_summary: str = "",
    ) -> Ticket:
        query = _clean(customer_query, 1000)
        if not query:
            raise TicketError("A ticket needs a description of the issue.")
        category = (category or "other").strip().lower()
        if category not in CATEGORIES:
            category = "other"
        priority = (priority or "normal").strip().lower()
        if priority not in PRIORITIES:
            priority = "normal"
        if category == "safety":
            priority = "high"
        pnr_clean = re.sub(r"\s+", "", str(pnr or "")).upper()
        if not _PNR_RE.match(pnr_clean):
            pnr_clean = ""
        self.path.parent.mkdir(parents=True, exist_ok=True)
        try:
            with self._lock():
                rows = self._read_rows()
                ticket = Ticket(
                    ticket_id=self._next_id(rows),
                    created_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
                    customer_query=query,
                    category=category,
                    reason=_clean(reason, 300) or CATEGORIES[category],
                    priority=priority,
                    pnr=pnr_clean,
                    conversation_summary=_clean(conversation_summary, 2000),
                )
                new_file = not self.path.exists() or self.path.stat().st_size == 0
                with self.path.open("a", newline="", encoding="utf-8") as f:
                    writer = csv.DictWriter(f, fieldnames=FIELDNAMES)
                    if new_file:
                        writer.writeheader()
                    writer.writerow(asdict(ticket))
                    f.flush()
                    os.fsync(f.fileno())
                # Read back to confirm the write before reporting success.
                if not any(r.get("ticket_id") == ticket.ticket_id for r in self._read_rows()):
                    raise TicketError("Ticket could not be verified after saving.")
        except OSError as exc:
            raise TicketError(f"Could not save the ticket: {exc}") from exc
        return ticket

    def list_tickets(self, status: str | None = None) -> list[dict]:
        rows = self._read_rows()
        if status:
            rows = [r for r in rows if r.get("status") == status]
        return rows

    def get_ticket(self, ticket_id: str) -> dict | None:
        return next((r for r in self._read_rows() if r.get("ticket_id") == ticket_id), None)
